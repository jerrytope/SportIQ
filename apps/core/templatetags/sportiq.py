@register.simple_tag
def icon(name, cls=""):
    body = ICONS.get(name, ICONS["help"])
    return format_html(
        '<svg class="icon {}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
        'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>',
        cls, mark_safe(body),
    )


ALLOWED_TAGS = ["p", "br", "strong", "em", "a", "ul", "ol", "li", "h2", "h3", "h4", "blockquote", "code", "pre",
                "hr", "img", "table", "thead", "tbody", "tr", "th", "td"]


@register.filter
def markdown(text):
    html = md.markdown(text or "", extensions=["extra", "sane_lists"])
    return mark_safe(bleach.clean(html, tags=ALLOWED_TAGS,
                                  attributes={"a": ["href", "title"], "img": ["src", "alt"]}))


@register.filter
def naira(kobo):
    try:
        value = int(kobo) / 100
    except (TypeError, ValueError):
        return ""
    return "Free" if value == 0 else f"₦{value:,.0f}"


@register.filter
def pct(value, total):
    try:
        return round(100 * float(value) / float(total)) if float(total) else 0
    except (TypeError, ValueError):
        return 0


@register.simple_tag(takes_context=True)
def qs(context, **kwargs):
    """Return the current query string with the given keys replaced (None removes)."""
    params = context["request"].GET.copy()
    for k, v in kwargs.items():
        if v in (None, ""):
            params.pop(k, None)
        else:
            params[k] = v
    params.pop("page", None) if "page" not in kwargs else None
    return "?" + params.urlencode() if params else "?"


@register.simple_tag(takes_context=True)
def active(context, prefix, exact=False):
    path = context["request"].path
    return "active" if (path == prefix if exact else path.startswith(prefix)) else ""


@register.filter
def has_role(user, roles):
    """{% if user|has_role:"registrar,finance_officer" %}"""
    return user.has_role(*[r.strip() for r in roles.split(",")]) if user.is_authenticated else False


@register.filter
def get_item(d, key):
    return d.get(key) if hasattr(d, "get") else None


@register.filter
def duration(minutes):
    try:
        minutes = int(minutes)
    except (TypeError, ValueError):
        return ""
    h, m = divmod(minutes, 60)
    return f"{h}h {m}m" if h and m else (f"{h}h" if h else f"{m} min")
